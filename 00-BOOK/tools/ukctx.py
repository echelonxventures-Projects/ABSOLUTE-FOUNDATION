def read_articles() -> list[dict]:
    """The articles of the root law, read from its only home.

    Restating an article here would be exactly the second authoring UCKP-ART-03
    voids, so the text is parsed out of engine/uckp/law.py rather than copied.

    Parsed with `ast`, not a regex over the source. The regex this replaced matched
    `Article("id", "title", "literal"...)` and therefore silently dropped UCKP-ART-01,
    whose text is the named constant SUPREMACY_CLAUSE: the law declares twenty articles
    and every agent surface carried nineteen, missing the one that establishes supremacy.
    A parser that understands names cannot lose an article for how it was spelled. This
    reads the module as text and never imports it — the law is authority, not a dependency.
    """
    tree = ast.parse(read_text(LAW))
    consts: dict[str, str] = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant) \
                and isinstance(node.value.value, str):
            for tgt in node.targets:
                if isinstance(tgt, ast.Name):
                    consts[tgt.id] = node.value.value

    def literal(node) -> str | None:
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            return node.value
        if isinstance(node, ast.Name):
            return consts.get(node.id)
        return None

    out = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                and node.func.id == "Article" and len(node.args) >= 3):
            continue
        ident, title, text = (literal(a) for a in node.args[:3])
        if not (ident and title and text) or not ident.startswith("UCKP-ART-"):
            continue
        out.append({"id": ident, "title": title, "text": " ".join(text.split())})
    return sorted(out, key=lambda a: a["id"])


def read_authority_roles(caa: dict) -> list[dict]:
    roles = []
    for name, spec in sorted(caa.get("authority_roles", {}).items()):
        roles.append({
            "role": name,
            "may_hold_authority": bool(spec.get("may_hold_authority")),
            "cardinality": spec.get("cardinality", ""),
            "definition": spec.get("definition", ""),
        })
    return roles


def read_exclusion_classes() -> list[dict]:
    reg = load_json(os.path.join(BOOK_DIR, "DATA", "exclusion-register.json"))
    return [{"class": k, "definition": v} for k, v in sorted(reg.get("classes", {}).items())]


def read_mutation_authorities() -> list[dict]:
    mgb = load_json(os.path.join(BOOK_DIR, "DATA", "mutation-governance-boundary.json"))
    out = []
    for a in mgb.get("authorities", []):
        out.append({
            "authority": a.get("authority", ""),
            "implementation": a.get("implementation", ""),
            "enforcement": a.get("enforcement", ""),
        })
    return sorted(out, key=lambda a: a["authority"])



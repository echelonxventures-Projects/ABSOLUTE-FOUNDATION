def compute_outputs() -> tuple[dict, dict]:
    """(relpath -> content). Pure: no writes, no clock, no environment."""
    decl = load_json(DECLARATION)
    caa = load_json(CAA)
    articles = read_articles()
    roles = read_authority_roles(caa)
    mut = read_mutation_authorities()
    excl = read_exclusion_classes()

    root = decl["context_root"]["path"]
    out: dict[str, str] = {}
    out[f"{root}/00-CONTEXT-INDEX.md"] = render_index(decl, articles, roles)
    for d in sorted(decl["domains"], key=lambda x: x["domain"]):
        out[f"{root}/{d['domain']}.md"] = render_domain(decl, d)

    body = None
    for s in sorted(decl["agent_surfaces"], key=lambda x: x["agent"]):
        body = render_agent(decl, s, articles, mut, excl)
        out[s["surface"]] = render_mdc(body) if s["format"] == "mdc" else body

    # THE ENTRY POINT IS DECLARED, NOT ASSUMED. `entry_points` names the files a reader
    # arrives at, and each one says which producer emits it. AGENTS.md is NOT emitted
    # here: it is an agent surface, so the loop above already wrote it with the same body
    # every other surface carries, and writing it twice would be the divergence INV-CTX-13
    # refuses. An entry point that names a surface is a cross-reference, never a second
    # rendering.
    renderers = {"README.md": render_readme}
    for path, entry in sorted(decl.get("entry_points", {}).items()):
        if entry.get("surface_binding"):
            continue
        if path not in renderers:
            raise SystemExit(
                f"REFUSED — entry point {path!r} is declared but no renderer emits it, and "
                "it binds to no agent surface either. A declared entry point nothing writes "
                "is a promise of a file that will never exist.")
        out[path] = renderers[path](decl)

    # THE DECLARED CLOSURE IS THE MEASURED CLOSURE (D-R6). This list used to be
    # computed from every domain's authority_home, which produced 14 entries of which
    # 9 were never opened — a declaration wider than the derivation, which is the
    # "stale declaration is a false assurance" defect UGA OBS-INV-12 polices elsewhere.
    # The set now comes from `true_input_set`, which was established by runtime tracing
    # (sys.addaudithook over `open`, cold start, outputs removed) rather than by reading
    # this file. A domain's authority_home is EXISTENCE-CHECKED by INV-CTX-02; being
    # checked for existence is not being read, and only what is read is an input.
    inputs = sorted(decl["true_input_set"]["inputs"])

    manifest = {
        "artifact_id": "UCOS-UCTX-MANIFEST-001",
        "title": ("Context Projection Manifest — every emitted surface, its digest "
                  "and its derivation"),
        "authority": ("NONE — DERIVED TRUTH. A measurement of what the producer "
                      "emitted. It records and asserts nothing."),
        "producer": decl["producer"]["home"],
        "declaration": rel(DECLARATION),
        "derives_from": inputs,
        "projections": [
            {"path": p, "sha256": digest(out[p]), "bytes": len(out[p].encode("utf-8")),
             "derives_from": inputs}
            for p in sorted(out)
        ],
    }
    out[f"{root}/MANIFEST.json"] = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    return out, decl


def write_outputs(out: dict) -> list[str]:
    changed = []
    for relpath in sorted(out):
        full = os.path.join(REPO, relpath)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        new = out[relpath]
        old = read_text(full) if os.path.isfile(full) else None
        if old != new:
            with open(full, "w", encoding="utf-8") as fh:
                fh.write(new)
            changed.append(relpath)
    return changed


def cmd_build(_args) -> int:
    out, _ = compute_outputs()
    changed = write_outputs(out)
    print(f"UCOS-UCTX-001 context build — {len(out)} projections")
    for c in changed:
        print(f"  wrote {c}")
    if not changed:
        print("  no change (fixed point)")
    return 0


def cmd_plan(_args) -> int:
    out, _ = compute_outputs()
    print(f"UCOS-UCTX-001 context plan — {len(out)} projections (READ-ONLY, nothing written)")
    n = 0
    for relpath in sorted(out):
        full = os.path.join(REPO, relpath)
        old = read_text(full) if os.path.isfile(full) else None
        state = "NEW" if old is None else ("CHANGED" if old != out[relpath] else "current")
        if state != "current":
            n += 1
        print(f"  [{state:8}] {relpath}")
    print(f"would write {n} file(s)")
    return 0


